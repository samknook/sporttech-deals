'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const core=require('../docs/ai-studio/pilot-scorecard-core.js');
const root=path.join(__dirname,'..');
const html=fs.readFileSync(path.join(root,'docs/ai-studio/pilot-meten.html'),'utf8');
const row=i=>({id:'T-'+i,before:'9',processing:'2',review:'3',rework:'1',correct:'yes',comparable:'yes'});
const small=core.assess([row(1),row(2),row(3)],{hourlyCost:'40'});
assert.equal(small.state,'insufficient-evidence');
assert.equal(small.approvedForProduction,false);
assert.equal(small.savedMinutes,9);
const twenty=Array.from({length:20},(_,i)=>row(i+1));
const good=core.assess(twenty,{hourlyCost:'40'});
assert.equal(good.state,'further-review');
assert.equal(good.eligible,20);
assert.equal(good.savedMinutes,60);
assert.equal(good.verifiedSavings,false);
assert.match(core.report(good),/menselijke controle/i);
assert.equal(core.assess(twenty.map((x,i)=>i===0?{...x,correct:'no'}:x)).state,'quality-block');
assert.equal(core.assess(twenty.map(x=>({...x,review:'15'}))).state,'no-net-gain');
assert.equal(core.assess(twenty.map((x,i)=>i<2?{...x,comparable:'yes'}:{...x,comparable:'no'})).state,'insufficient-evidence');
assert.throws(()=>core.assess([row(1),row(1),row(3)]),/uniek/);
assert.throws(()=>core.assess([row(1),row(2)]),/3 tot 200/);
assert.throws(()=>core.assess([{...row(1),review:'-1'},row(2),row(3)]),/Ongeldig/);
assert.match(html,/<html lang="nl">/);
assert.match(html,/src="pilot-scorecard-core.js"/);
assert.match(html,/niets op/i);
assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|localStorage\.|sessionStorage\.|mailto:/);
console.log('Pilot scorecard tests passed. Synthetic tasks only.');
