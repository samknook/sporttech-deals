'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const core=require('../docs/ai-studio/lead-brief-core.js');
const html=fs.readFileSync(path.join(root,'docs/ai-studio/kennismaking.html'),'utf8');
const home=fs.readFileSync(path.join(root,'docs/ai-studio/index.html'),'utf8');
const pilot=fs.readFileSync(path.join(root,'docs/ai-studio/pilot.html'),'utf8');
const sample={type:'B2B groothandel of leverancier',size:'5–20 medewerkers',task:'Vragen over facturen en betalingen',volume:'75',goal:'Minder tijd kwijt aan terugkerende vragen',urgent:false};
const result=core.build(sample);
assert.equal(result.readyToSend,false);
assert.equal(result.sent,false);
assert.equal(result.stored,false);
assert.match(result.fullText,/75 per week/);
assert.match(result.fullText,/Met vriendelijke groet/);
assert.match(result.fullText,/contactgegevens zelf toevoegen/);
assert.throws(()=>core.build({...sample,volume:'bad'}));
assert.throws(()=>core.build({...sample,volume:'-1'}));
assert.throws(()=>core.build({...sample,goal:''}));
assert.match(core.build({...sample,type:'Ik heb een eigen API\/ERP-koppeling nodig'}).fullText,/Maatwerkonderzoek/);
assert.match(home,/href="kennismaking.html"/);
assert.match(pilot,/href="kennismaking.html"/);
assert.match(html,/src="lead-brief-core.js"/);
assert.match(html,/navigator.clipboard/);
assert.match(html,/niets verzonden/i);
assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|localStorage\.|sessionStorage\.|mailto:/);
assert.doesNotMatch(html,/name="email"|name="phone"/);
console.log('MKB AI Studio locally prepared contact brief tests passed.');
