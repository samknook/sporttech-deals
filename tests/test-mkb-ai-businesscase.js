'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const core=require('../docs/ai-studio/businesscase-core.js');
const html=fs.readFileSync(path.join(root,'docs/ai-studio/businesscase.html'),'utf8');
const home=fs.readFileSync(path.join(root,'docs/ai-studio/index.html'),'utf8');
const packages=fs.readFileSync(path.join(root,'docs/ai-studio/pakketten.html'),'utf8');
const data={weeklyMessages:120,repeatPercent:60,adoptionPercent:70,beforeMinutes:8,aiProcessingMinutes:1.5,reviewMinutes:2.5,reworkMinutes:1,weeklyOverheadMinutes:20,hourlyCost:40,licenseMonthly:40,careMonthly:199,setupCost:995,criticalErrors:0};
const r=core.calculate(data);
assert.equal(r.eligibleWeekly,50.4);
assert.ok(r.savedMinutes>0);
assert.ok(r.netMonthlyValue>0);
assert.ok(r.year1Net>0);
assert.equal(r.status,'worth-testing');
assert.equal(r.readyForProduction,false);
assert.equal(r.customerValueVerified,false);
assert.equal(core.calculate({...data,criticalErrors:1}).status,'do-not-deploy');
assert.equal(core.calculate({...data,reviewMinutes:20}).status,'do-not-deploy');
assert.equal(core.calculate({...data,licenseMonthly:1000}).status,'do-not-deploy');
assert.equal(core.calculate({...data,repeatPercent:0}).status,'do-not-deploy');
assert.equal(core.calculate({...data,weeklyMessages:10}).status,'do-not-deploy');
assert.throws(()=>core.calculate({...data,weeklyMessages:''}),/Controleer/);
assert.throws(()=>core.calculate({...data,adoptionPercent:101}),/Controleer/);
assert.match(core.report(r),/geen gerealiseerde besparing|geen gerealiseerde besparing/i);
assert.match(html,/src="businesscase-core.js"/);
assert.match(html,/menselijke beoordeling/i);
assert.match(html,/fouten in de proef/i);
assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|localStorage\.|sessionStorage\.|mailto:/);
assert.match(home,/href="businesscase.html"/);
assert.match(packages,/href="businesscase.html"/);
console.log('AI Inbox business-case checks passed. No network or customer data.');
