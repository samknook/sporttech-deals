/* Run: node tests/test-mkb-ai-review-pipeline.js */
'use strict';
const assert=require('node:assert/strict');
const pipe=require('../ventures/mkb-ai-studio/api-pilot/review-pipeline.cjs');
const sample={id:'PILOT-001',message:'Check invoice INV-218',approvedFacts:[{source:'Synthetic invoice list',fact:'INV-218 is in the demo ledger; status not shared with assistant.'}]};
const assertion={kind:'invoice',reference:'INV-218',field:'payment_status',value:'unpaid'};
const record={...assertion,source:'Synthetic ledger',checkedOn:'2026-11-06'};
const safeDraft='CATEGORY: invoice\nDRAFT: We will investigate invoice INV-218 and follow up after reviewing the records.\nHUMAN CHECKS: Confirm customer and invoice status in the approved system.';
const base={sample,draft:safeDraft,assertions:[assertion],records:[record],asOf:'2026-11-06'};
const clean=pipe.prepare(base);
assert.equal(clean.state,'pending-review');assert.deepEqual(clean.problems,[]);
assert.equal(clean.comparison.results[0].status,'matched');
assert.equal(pipe.summary(clean).sent,false);
assert.throws(()=>pipe.review(clean,{decision:'approve-draft',reviewer:'Supervisor'}),/verify source/);
const reviewed=pipe.review(clean,{decision:'approve-draft',reviewer:'Supervisor',sourceVerified:true});
assert.equal(reviewed.state,'reviewed-draft');assert.equal(reviewed.sendEnabled,false);
assert.throws(()=>pipe.review(reviewed,{decision:'approve-draft',reviewer:'Supervisor',sourceVerified:true}));
const contrary=pipe.prepare({...base,assertions:[{...assertion,value:'paid'}]});
assert.ok(contrary.problems.includes('evidence:contradicted'));
assert.throws(()=>pipe.review(contrary,{decision:'approve-draft',reviewer:'Supervisor',sourceVerified:true}),/Unresolved/);
const escalated=pipe.review(contrary,{decision:'escalate',reviewer:'Supervisor',reason:'Payment status differs from source'});
assert.equal(escalated.state,'escalated');assert.equal(escalated.sendEnabled,false);
assert.throws(()=>pipe.review(contrary,{decision:'escalate',reviewer:'Supervisor'}),/reason/);
const badDraft=pipe.prepare({...base,draft:'Payment has been received for INV-218.'});
assert.ok(badDraft.problems.some(x=>x.startsWith('format:')));
assert.ok(badDraft.problems.includes('claim:confirmed-payment'));
const stale=pipe.prepare({...base,records:[{...record,checkedOn:'2026-10-01'}]});
assert.ok(stale.problems.includes('evidence:stale'));
const absent=pipe.prepare({...base,records:[]});
assert.ok(absent.problems.includes('evidence:missing'));
console.log('Integrated synthetic inbox approval pipeline tests passed; no external actions.');
