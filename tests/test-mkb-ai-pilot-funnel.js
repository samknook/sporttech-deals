'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const fit=require('../docs/ai-studio/pilot-fit-core.js');
const html=fs.readFileSync(path.join(root,'docs/ai-studio/pilot.html'),'utf8');
const home=fs.readFileSync(path.join(root,'docs/ai-studio/index.html'),'utf8');
const detail=fs.readFileSync(path.join(root,'docs/ai-studio/wat-krijg-je.html'),'utf8');
const docs=fs.readFileSync(path.join(root,'ventures/mkb-ai-studio/PAID_PILOT_EXECUTION.md'),'utf8');
const base={weeklyMessages:75,minutesPerMessage:6,repetition:'yes',source:'digital',owner:true,sensitive:false,needsIntegration:false};
const ideal=fit.evaluate(base);
assert.equal(ideal.route,'starter');
assert.equal(ideal.priceIndicative,995);
assert.equal(ideal.baselineHours,7.5);
assert.equal(ideal.potentialSavings,null);
assert.equal(ideal.contract,false);
assert.equal(fit.evaluate({...base,needsIntegration:true}).route,'custom-review');
assert.equal(fit.evaluate({...base,sensitive:true}).route,'custom-review');
assert.equal(fit.evaluate({...base,owner:false}).route,'custom-review');
assert.equal(fit.evaluate({...base,source:'none'}).route,'custom-review');
assert.equal(fit.evaluate({...base,weeklyMessages:4}).route,'quickscan');
assert.equal(fit.evaluate({...base,repetition:'no'}).route,'quickscan');
assert.throws(()=>fit.evaluate({...base,weeklyMessages:-1}),/Ongeldige/);
assert.throws(()=>fit.evaluate({...base,minutesPerMessage:500}),/Ongeldige/);
assert.match(fit.summary(ideal),/niets besteld of verstuurd/i);
assert.match(html,/<html lang="nl">/);
assert.match(html,/name="viewport"/);
assert.match(html,/pilot-fit-core.js/);
assert.match(html,/navigator\.clipboard/);
assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|localStorage\./);
assert.match(html,/nog geen gekoppeld contactformulier/i);
assert.match(home,/href="pilot.html"/);
assert.match(detail,/href="pilot.html"/);
assert.match(docs,/€995/);
console.log('MKB AI Studio first pilot funnel tests passed.');
