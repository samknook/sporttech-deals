'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs');
const read=p=>fs.readFileSync(p,'utf8');
const signup=read('supabase/functions/trizentro-email-radar/index.ts');
const dispatch=read('supabase/functions/trizentro-radar-dispatch/index.ts');
const alerts=read('docs/raceatlas/alerts.js');
const manage=read('docs/raceatlas/alerts-beheren.html');
const schedule=read('.github/workflows/trizentro-radar-email.yml');
const release=read('docs/raceatlas/index.html');
const must=(ok,message)=>assert.ok(ok,message);
must(signup.includes('RADAR_EMAIL_LIVE')&&signup.includes('RESEND_API_KEY')&&signup.includes('RESEND_FROM')&&signup.includes('RADAR_CRON_SECRET'),'Signup must require fully configured email delivery');
must(signup.includes("if(action==='subscribe')")&&signup.includes("email_not_configured"),'Subscription must fail closed when disabled');
must(signup.includes("if(action==='confirm'||action==='unsubscribe')"),'Confirmation and opt-out actions must remain available');
must(signup.includes("const signed=action==='unsubscribe'"),'Unsubscribe must support durable signed tokens');
must(signup.includes("unsubscribe|"),'HMAC opt-out signature missing');
must(signup.includes('if(!origin||!origins.has(origin))'),'Email endpoint must whitelist origins');
must(signup.includes("await db('trizentro_email_alerts?on_conflict=email,event_id'"),'Subscription must be stored');
must(signup.indexOf("const write=await db('trizentro_email_alerts?on_conflict=email,event_id'")<signup.indexOf("const sent=await send(email"),'Persist token before sending confirmation');
must(!signup.includes("return answer(origin,200,{ok:true,message:'confirmed'})"),'Do not fake confirmation response');
must(dispatch.includes("trustedEvidence"),'Notifications must require reliable organizer evidence');
must(dispatch.includes("signedUnsubscribe"),'Dispatcher must include persistent opt-out link');
must(!dispatch.includes('unsubscribe_token_hash:newHash'),'Dispatcher must never invalidate prior unsubscribe tokens');
must(dispatch.includes('trizentro_radar_deliveries'),'Dispatcher must prevent duplicate sends');
must(dispatch.includes('RADAR_CRON_SECRET'),'Dispatcher needs a secret');
must(schedule.includes('secrets.TRIZENTRO_RADAR_CRON_SECRET'),'Scheduler must be disabled without configured secret');
must(alerts.includes("data.enabled===true"),'Web UI must only show signup if delivery is active');
must(alerts.includes('emailForm.hidden=true'),'Signup form must be hidden by default');
must(manage.includes('noindex,nofollow')&&manage.includes('no-referrer'),'Token landing page privacy protections required');
must(manage.includes("history.replaceState(null,'',location.pathname)"),'One-time tokens must be removed from the browser address bar');
must(release.includes('alerts.js?v='),'Event homepage must load alert dialog module');
new Function(alerts);
