'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const core=require('../docs/ai-studio/prospect-fit-core.js');
const html=fs.readFileSync(path.join(__dirname,'../docs/ai-studio/prospecten.html'),'utf8');
const base={sector:'b2b-wholesale',volume:'75-plus',repetition:'high',sources:'approved-digital',reviewer:'yes',integrations:'none',sensitive:'no',budget:'995-plus',decision:'decision-maker'};
const good=core.assess(base);
assert.equal(good.score,100);
assert.equal(good.fit,'starter-candidate');
assert.equal(good.canOfferStandard,true);
assert.equal(good.actualCustomer,false);
assert.equal(good.requestSent,false);
assert.equal(good.productionApproved,false);
assert.match(core.brief(good,'DEMO-123'),/DEMO-123/);
assert.match(core.brief(good,'DEMO-123'),/geen e-mail verstuurd/i);
assert.throws(()=>core.brief(good,'bedrijf@example.com'),/anonymous codes/);
assert.throws(()=>core.brief(good,'Bedrijf Naam'),/anonymous codes/);
assert.equal(core.assess({...base,integrations:'erp-write'}).fit,'review-required');
assert.equal(core.assess({...base,budget:'unknown'}).fit,'discovery-needed');
assert.equal(core.assess({...base,budget:'295-994'}).fit,'discovery-needed');
assert.equal(core.assess({...base,budget:'under-295'}).fit,'low-fit');
assert.equal(core.assess({...base,decision:'researcher'}).fit,'discovery-needed');
assert.equal(core.assess({...base,sensitive:'yes'}).fit,'review-required');
assert.equal(core.assess({...base,reviewer:'no'}).fit,'review-required');
assert.equal(core.assess({...base,sources:'none'}).fit,'review-required');
assert.equal(core.assess({...base,sector:'other',sources:'manual',volume:'under-20',repetition:'low'}).fit,'low-fit');
assert.throws(()=>core.assess({...base,volume:'20000'}),/Invalid input/);
assert.match(html,/src="prospect-fit-core.js"/);
assert.match(html,/<meta name="viewport"/);
assert.doesNotMatch(html,/fetch\s*\(|XMLHttpRequest|localStorage\.|sessionStorage\.|mailto:/);
assert.match(html,/geen aanmeldformulier/i);
console.log('Prospect sales cockpit checks passed; no personal-data backend.');
