'use strict';
const assert=require('node:assert/strict');
const wf=require('../docs/ai-studio/inbox-workflow-core.js');
let q=wf.create();
assert.equal(q.length,4);assert.equal(wf.stats(q).new,4);assert.equal(wf.stats(q).sent,0);
