'use strict';
const fs=require('node:fs'),assert=require('node:assert/strict');
const src=fs.readFileSync('docs/shared-ui.js','utf8');
new Function(src);
const pages=JSON.parse(fs.readFileSync('config/trizentro-public-pages.json','utf8')).pages.map(x=>'docs/'+x);
for(const file of pages){
 const html=fs.readFileSync(file,'utf8');
 assert.ok(html.includes('shared-ui.js?v='),file+' missing shared navigation');
 assert.ok(html.includes('shared-ui.css?v='),file+' missing shared style');
 assert.ok(html.includes('tz-logo-image'),file+' missing shared brand');
}
for(const id of ['events','season','performance','account','organizers'])assert.ok(src.includes("id:'"+id+"'"),'missing destination '+id);
assert.ok(src.includes('const preservedLanguage='),'language selector lost');
assert.ok(src.includes('const bottom=document.createElement'), 'unified mobile navigation missing');
assert.ok(src.includes("document.getElementById('navSaved')?.click()"),'saved season functionality lost');
assert.ok(src.includes("document.getElementById('raAccountNav')"),'account navigation lost');
assert.ok(src.includes('if(item.id===\'organizers\')'),'organizers must be the final nav destination');
assert.ok(src.includes("window.addEventListener('raceatlas:languagechange',updatePlatformLanguage)"),'menu does not update after language switching');
assert.ok(src.includes("const queryLang=new URLSearchParams(location.search).get('lang');"),'language must be read dynamically');
assert.ok(src.includes("const label=el.querySelector('.tz-tab-label')"),'mobile labels must update with language');
const css=fs.readFileSync('docs/shared-ui.css','utf8');
assert.ok(src.includes("const isPerformance=/\\/performance\\/?$/.test(path)"),'clean Performance route not active');
assert.ok(src.includes("if(active)el.setAttribute('aria-current','page')"),'aria-current activation missing');
assert.ok(css.includes('a[data-tz-destination][aria-current="page"]'),'active page CSS missing');
assert.ok(css.includes('body.tz-performance .tz-page-main'),'Performance grid alignment CSS missing');
const perf=fs.readFileSync('docs/performance.html','utf8');
assert.ok(perf.includes("url.searchParams.set('sport',s)"),'sport selector must preserve canonical Performance URL');
assert.ok(perf.includes("url.pathname+url.search+url.hash"),'sport selection must use an absolute path, not the HTML base URL');
assert.ok(!perf.includes("history.replaceState(null,'','?sport='+s)"),'regression: relative sport URL removes /performance/ path');
console.log('PASS: TriZentro pages share functional and mobile-safe navigation');
