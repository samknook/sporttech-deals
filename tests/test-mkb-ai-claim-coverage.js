'use strict';
const assert=require('node:assert/strict');
const {coverage}=require('../ventures/mkb-ai-studio/api-pilot/claim-coverage.cjs');
const {validate}=require('../ventures/mkb-ai-studio/api-pilot/linked-claims.cjs');
const field={kind:'invoice',reference:'INV-218',field:'payment_status',value:'unpaid'};
const source={...field,source:'Synthetic ledger',checkedOn:'2026-11-06'};
const make=(draft,quote)=>({draft,claims:[{quote,evidence:field}]});
const quoted='Invoice INV-218 has status unpaid';
const base=quoted+'. We will review this with a colleague.';
const clear=validate(make(base,quoted),[source],'2026-11-06');
assert.equal(clear.issues.length,0);
assert.equal(clear.claimsComplete,false);
const hidden=validate(make(base+' Your refund of EUR 250.00 has been processed.',quoted),[source],'2026-11-06');
assert.ok(hidden.issues.includes('unlinked:amount'));
assert.ok(hidden.issues.includes('unlinked:refund-assertion'));
const extraRef=validate(make(base+' Order ORD-999 will arrive tomorrow.',quoted),[source],'2026-11-06');
assert.ok(extraRef.issues.includes('unlinked:reference'));
assert.ok(extraRef.issues.includes('unlinked:delivery-assertion'));
const extraDate=coverage(base+' Due 2026-12-01',[{quote:quoted}]);
assert.ok(extraDate.findings.some(f=>f.kind==='date'));
const account=coverage(base+' Bank details updated.',[{quote:quoted}]);
assert.ok(account.findings.some(f=>f.kind==='bank-change'));
assert.equal(clear.approvedForSending,false);
assert.equal(hidden.approvedForSending,false);
console.log('Unlinked business fact coverage tests passed. No model or network calls.');
