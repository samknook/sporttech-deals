'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const root='docs/raceatlas/';
const html=fs.readFileSync(root+'index.html','utf8');
const alert=fs.readFileSync(root+'alerts.js','utf8');
const intel=fs.readFileSync(root+'intelligence.js','utf8');
const manager=fs.readFileSync(root+'alerts-beheren.html','utf8');
const signup=fs.readFileSync('supabase/functions/trizentro-email-radar/index.ts','utf8');
const dispatch=fs.readFileSync('supabase/functions/trizentro-radar-dispatch/index.ts','utf8');
const workflow=fs.readFileSync('.github/workflows/trizentro-radar-email.yml','utf8');
assert.ok(html.includes('alerts.js?v=20261112-email2'));
assert.ok(html.includes('intelligence.js?v=20261112-email2'));
assert.doesNotThrow(()=>new Function(alert));
assert.doesNotThrow(()=>new Function(intel));
assert.ok(alert.includes("data.enabled===true"),'Email form must remain hidden when backend disabled');
assert.ok(alert.includes("input.type='email'"),'Email address input required');
assert.ok(manager.includes('name="referrer" content="no-referrer"'),'Do not leak private token through Referer');
assert.ok(manager.includes('history.replaceState(null'),'Remove token from address bar');
assert.ok(!manager.includes('onload="'),'No automatic confirm or unsubscribe');
assert.ok(signup.includes("Deno.env.get('RADAR_EMAIL_LIVE')==='true'"),'Do not accept email signups without active sending');
assert.ok(signup.includes("Deno.env.get('RADAR_CRON_SECRET')"),'Signup requires dispatch capability');
assert.ok(signup.includes("if(!enabled)return answer(origin,503"),'Disabled mode must reject signups');
assert.ok(signup.includes("action==='confirm'")&&signup.includes("action==='unsubscribe'"),'Double opt-in and unsubscribe both required');
assert.ok(signup.includes("state:'pending'")&&signup.includes("state:'confirmed'"),'No auto-confirmation');
assert.ok(signup.includes("rateHash=await hash"),'Abuse protections required');
assert.ok(dispatch.includes("priorSent.length"),'Idempotent dispatch required');
assert.ok(dispatch.includes("race.date_confidence==='official'"),'Official race date evidence required');
assert.ok(dispatch.includes("last_verified_at")&&dispatch.includes("verified_at"),'Verified-source change gate required');
assert.ok(workflow.includes("secrets.TRIZENTRO_RADAR_CRON_SECRET"),'Scheduled trigger secret required');
console.log('TriZentro email radar: strict activation gate, double opt-in, unsubscribe and change dispatch checks passed');
